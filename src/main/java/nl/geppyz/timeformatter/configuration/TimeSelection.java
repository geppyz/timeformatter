package nl.geppyz.timeformatter.configuration;

/**
 * Selection of time units to be displayed.
 */
public enum TimeSelection {
  /**
   * Only seconds
   */
  ONLY_SECONDS,
  /**
   * Minutes and seconds
   */
  MINUTES_AND_SECONDS,
  /**
   * Hours, minutes and seconds
   */
  HOURS_MINUTES_AND_SECONDS
}
